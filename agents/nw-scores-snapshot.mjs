// agents/nw-scores-snapshot.mjs
// Two jobs, both needing only NEURONWRITER_API_KEY (read-only, zero analysis quota):
//
//   node agents/nw-scores-snapshot.mjs --probe
//       Resolves the OPEN base-path question. POSTs `list-queries` to BOTH
//       `/neuron-api/0.5` (shared client) and `/neuron-api/0.5/writer` (narrator)
//       and prints which returns 200.
//
//       RUN THIS IN GITHUB ACTIONS (nw workflows) — the only place a VALID
//       NEURONWRITER_API_KEY lives. A local run returns 401 on BOTH bases
//       (the key in ~/.env is invalid/inactive as of 2026-07-16), which proves
//       nothing about the paths.
//
//       STATUS 2026-07-16: do NOT flip the shared client to /writer on assumption.
//       Evidence says the CURRENT base (/0.5, no /writer) WORKS: neuronwriter-qa
//       imports analyzePageContent from lib/neuronwriter.mjs (BASE=/0.5), whose
//       post() throws on any non-2xx, and the 2026-07-13 QA run returned 17+ real
//       API content_scores (27..56/100). It also hit real 429 "analyses exceeded"
//       quota errors — impossible against a 404. Change the base only if this
//       probe proves otherwise with a valid key.
//
//   node agents/nw-scores-snapshot.mjs
//       Calls list-queries on the working base and writes a committed snapshot to
//       agents/reports/nw-queries-latest.json so per-URL/keyword scores live in git
//       (today they only exist in Supabase/Notion/CI artifacts).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = "https://app.neuronwriter.com/neuron-api/0.5";
const PROJECT = process.env.NEURONWRITER_PROJECT || "9d0bec3a70f4743c";
const KEY = process.env.NEURONWRITER_API_KEY;
if (!KEY) { console.error("FATAL: NEURONWRITER_API_KEY not set."); process.exit(1); }

async function call(base, method, body) {
  const res = await fetch(`${base}/${method}`, {
    method: "POST",
    headers: { "X-API-KEY": KEY, "Content-Type": "application/json", Accept: "application/json" },
    body: JSON.stringify(body || {}),
  });
  const text = await res.text();
  let json; try { json = JSON.parse(text); } catch { json = { _raw: text.slice(0, 300) }; }
  return { status: res.status, ok: res.ok, json };
}

async function probe() {
  const bases = { "no /writer (shared client, PROVEN working)": ROOT, "/writer (narrator + scripts)": `${ROOT}/writer` };
  console.log("Probing list-queries on both base paths...\n");
  let winner = null;
  for (const [label, base] of Object.entries(bases)) {
    try {
      const r = await call(base, "list-queries", { project: PROJECT });
      const n = Array.isArray(r.json) ? r.json.length : (Array.isArray(r.json?.queries) ? r.json.queries.length : "?");
      console.log(`  ${r.ok ? "PASS" : "FAIL"} ${r.status}  ${label}  ${base}  ${r.ok ? `(${n} queries)` : JSON.stringify(r.json).slice(0, 120)}`);
      if (r.ok && !winner) winner = { label, base };
    } catch (e) {
      console.log(`  ERR  ${label}  ${base}  ${String(e.message).slice(0, 120)}`);
    }
  }
  if (!winner) {
    console.log("\n=> Neither base returned 200. If BOTH say 401 the KEY is invalid/inactive — that is an auth problem, not a path problem. Fix the key first; this tells you nothing about the base.");
  } else {
    console.log(`\n=> Working base: ${winner.base}`);
    console.log("   If BOTH pass, the paths are aliases and no change is needed.");
    console.log("   Only change lib/neuronwriter.mjs if /0.5 FAILS and /writer PASSES with a valid key.");
  }
  return winner;
}

async function snapshot() {
  const w = await probe();
  const base = w?.base || ROOT;
  const r = await call(base, "list-queries", { project: PROJECT });
  if (!r.ok) { console.error("list-queries failed on the working base; aborting snapshot."); process.exit(1); }
  const rows = Array.isArray(r.json) ? r.json : (r.json?.queries || []);
  const snap = {
    _comment: "Committed snapshot of NeuronWriter queries for project " + PROJECT + ". Generated by agents/nw-scores-snapshot.mjs.",
    generated_from_base: base,
    project: PROJECT,
    count: rows.length,
    queries: rows.map((q) => ({
      query: q.query ?? q.query_id ?? q.id ?? null,
      keyword: q.keyword ?? null,
      created: q.created ?? null,
      score: q.content_score ?? q.score ?? null,
      url: q.url ?? null,
    })),
  };
  const __dir = dirname(fileURLToPath(import.meta.url));
  const out = join(__dir, "reports", "nw-queries-latest.json");
  writeFileSync(out, JSON.stringify(snap, null, 2) + "\n");
  const scored = snap.queries.filter((q) => typeof q.score === "number");
  const over80 = scored.filter((q) => q.score >= 80);
  console.log(`\nWrote ${out}  (${snap.count} queries, ${scored.length} with a score, ${over80.length} >= 80).`);
  if (over80.length) { console.log("  >= 80:"); over80.forEach((q) => console.log(`    ${q.score}  ${q.keyword}`)); }
}

(process.argv.includes("--probe") ? probe() : snapshot()).catch((e) => { console.error(e); process.exit(1); });
